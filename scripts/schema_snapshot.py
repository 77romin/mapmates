"""Materialize the complete DDL artifact from the baseline plus append-only migrations."""
from pathlib import Path
import argparse
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
files=[Path('db/schema.sql'),*sorted(Path('db/migrations').glob('*.sql'))]
text='-- Generated by scripts/schema_snapshot.py; edit baseline/migrations instead.\n'+''.join('\n-- SOURCE: '+str(p)+'\n'+p.read_text()+'\n' for p in files)
text=text.rstrip()+'\n'
target=Path('db/schema-current.sql')
if args.check:
 if not target.exists() or target.read_text()!=text:raise SystemExit('DDL snapshot is stale; run python3 scripts/schema_snapshot.py')
 print('PASS current DDL matches baseline and migrations')
else:target.write_text(text);print('WROTE',target)
